/**
 * Expands products with verified size variants into individual product listings.
 * Each size listing maintains direct purchasing capability, distinct SKU, dimension pill,
 * authentic price, and links directly to Level 5 Product Detail Page.
 */
export function expandProductSizeListings(productsList = []) {
  if (!Array.isArray(productsList)) return [];
  const expanded = [];
  productsList.forEach((prod) => {
    if (!prod) return;
    const variants = prod.variants;
    if (!variants || variants.length === 0) {
      expanded.push(prod);
      return;
    }
    variants.forEach((v) => {
      const dim = v.dimensions || (prod.specs && (prod.specs["Dimensions"] || prod.specs["Thread Size"])) || null;
      const sizeTitle = dim ? `${prod.name} — ${dim}` : prod.name;
      expanded.push({
        ...prod,
        id: `${prod.id}__${v.id}`,
        baseProductId: prod.id,
        variantId: v.id,
        selectedVariantId: v.id,
        selectedVariant: v,
        name: prod.name,
        displayName: sizeTitle,
        sku: v.sku || prod.sku,
        partNumber: v.partNumber || prod.partNumber,
        price: v.price !== undefined && v.price !== null ? v.price : prod.price,
        mrp: v.price !== undefined && v.price !== null ? Math.round(v.price * 1.25) : prod.mrp,
        dimensions: dim,
        unit: v.packSize || prod.unit || "Pack",
        stockQuantity: v.stockQuantity !== undefined ? v.stockQuantity : 100,
        inStock: v.inStock !== false && prod.inStock !== false,
        isSizeListing: true,
      });
    });
  });
  return expanded;
}
